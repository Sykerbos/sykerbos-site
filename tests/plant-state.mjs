import assert from 'node:assert/strict';
import {plantState} from '../plant-state.js';
const now=Date.parse('2026-10-18T07:00:00Z');
const row=(minutes,weight)=>({weight_g:weight,measured_at:new Date(now-minutes*60000).toISOString(),run_id:'one'});
const plant={learned_saturated_g:629,provisional_saturated_g:720,provisional_dry_g:525};
const history=[row(80,530),row(60,11.5),row(40,656.2),row(20,633.4),row(0,629)];
const full=plantState(plant,history,{now});
assert.equal(full.percent,100);assert.equal(full.angle,495);assert.equal(full.low,530);assert.equal(full.high,656.2);
assert.equal(full.rate,null);assert.equal(full.days,null);assert.equal(full.wet,629);
const dry=plantState(plant,[row(0,525)],{now});assert.equal(dry.state,'low');assert.equal(dry.percent,0);assert.equal(dry.angle,225);
const half=plantState(plant,[row(0,577)],{now});assert.equal(half.percent,50);assert.equal(half.angle,360);
const removed=plantState(plant,[...history,row(-1,0)],{now});assert.equal(removed.percent,null);assert.equal(removed.angle,null);
const stale=plantState(plant,[row(100,629)],{now});assert.equal(stale.percent,null);assert.equal(stale.days,null);
const offline=plantState(plant,history,{now,maintenance:true});assert.equal(offline.percent,null);
const unknown=plantState({},[row(0,629)],{now});assert.equal(unknown.percent,null);
const start=now-4*86400000;
const continuous=Array.from({length:289},(_,i)=>({weight_g:660-i*.1,measured_at:new Date(start+i*1200000).toISOString(),run_id:'one'}));
const measured=plantState(plant,continuous,{now});assert.ok(measured.usage.rate>7&&measured.usage.rate<7.4);assert.ok(measured.days>14&&measured.days<15);
console.log('Passed: distinct dry/mid/full radial positions, independent wet reference, empty exclusion, post-refill rate reset, stale/removed/maintenance states and measured-use projection.');
