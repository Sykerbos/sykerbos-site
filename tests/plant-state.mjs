import assert from 'node:assert/strict';
import {plantState} from '../plant-state.js';
import {collectionDemo} from '../collection-demo.js';
import {collectionModel} from '../collection-model.js';
import {plantTrendModel} from '../plant-trend-model.js';
import {plantDrydownGauge} from '../plant-drydown-gauge.js';
import {plantActivity} from '../plant-activity.js';
import {reservePercentLabel,waterPlan} from '../watering-model.js';
const now=Date.parse('2026-10-18T07:00:00Z');
const row=(minutes,weight)=>({weight_g:weight,measured_at:new Date(now-minutes*60000).toISOString(),run_id:'one'});
const plant={learned_saturated_g:629,provisional_saturated_g:720,provisional_dry_g:525};
const history=[row(80,530),row(60,11.5),row(40,656.2),row(20,633.4),row(0,629)];
const full=plantState(plant,history,{now});
assert.equal(full.percent,100);assert.equal(full.angle,495);assert.equal(full.low,530);assert.equal(full.high,656.2);
assert.equal(full.rate,null);assert.equal(full.days,null);assert.equal(full.wet,629);
const dry=plantState(plant,[row(0,525)],{now});assert.equal(dry.state,'reference');assert.equal(dry.percent,null);assert.equal(dry.angle,null);assert.equal(dry.days,null);
const half=plantState(plant,[row(0,577)],{now});assert.equal(half.percent,50);assert.equal(half.angle,360);
const removed=plantState(plant,[...history,row(-1,0)],{now});assert.equal(removed.percent,null);assert.equal(removed.angle,null);
const stale=plantState(plant,[row(100,629)],{now});assert.equal(stale.percent,null);assert.equal(stale.days,null);
const offline=plantState(plant,history,{now,maintenance:true});assert.equal(offline.percent,null);
const unknown=plantState({},[row(0,629)],{now});assert.equal(unknown.percent,null);
const start=now-4*86400000;
const continuous=Array.from({length:289},(_,i)=>({weight_g:660-i*.1,measured_at:new Date(start+i*1200000).toISOString(),run_id:'one'}));
const measured=plantState(plant,continuous,{now});assert.ok(measured.usage.rate>7&&measured.usage.rate<7.4);assert.ok(measured.days>14&&measured.days<15);
const sample=collectionDemo('below-reference').find(p=>p.id==='demo-b');
const demoNow=Date.parse(sample.history.at(-1).measured_at);
const comparison=collectionModel(sample,sample.history,{now:demoNow});
const below=comparison.view;
assert.equal(comparison.label,'Learning reserve');
assert.equal(below.setupRetired,true);
assert.equal(below.dry,null);
assert.equal(below.referenceReached,false);
assert.equal(comparison.percent,null);
assert.equal(below.days,null);
assert.ok(below.rate>0);
assert.ok(below.previousLow.weight>516&&below.previousLow.weight<518);
assert.ok(below.abovePreviousLow>2&&below.abovePreviousLow<4);
const dial=plantDrydownGauge(below,629);
assert.equal(dial.label,'Drying down');
assert.equal(dial.low,below.previousLow.weight);
assert.equal(dial.full,629);
assert.ok(dial.angle>225&&dial.angle<=258);
assert.equal(dial.slowed,true);
assert.equal(dial.newLow,false);
assert.equal(plantDrydownGauge(below,null).angle,null);
const lower=Array.from({length:144},(_,i)=>({...sample.history.at(-1),
  measured_at:new Date(demoNow+(i+1)*1200000).toISOString(),weight_g:519.6-(i+1)*.034}));
const newLow=plantState(sample,[...sample.history,...lower],{now:Date.parse(lower.at(-1).measured_at)});
assert.equal(plantDrydownGauge(newLow,629).newLow,true);
assert.equal(newLow.observedLow.weight,dial.low);
const trend=plantTrendModel(sample.history,below);
const forecast=trend.forecast;
assert.ok(forecast.at(-1).w<forecast[0].w);
const timeline=plantActivity(below,dial,trend.cycles,sample.history);
assert.deepEqual(timeline.map(e=>e.kind),['dry','water','cycle']);
assert.match(timeline[0].copy,/above the observed low/);
assert.match(timeline[1].copy,/The pot gained/);
const gapReadings=sample.history.filter(r=>{
  const age=demoNow-Date.parse(r.measured_at);
  return age<48*3600000||age>52*3600000;
});
const withGap=plantState(sample,gapReadings,{now:demoNow});
assert.equal(plantActivity(withGap,plantDrydownGauge(withGap,629),trend.cycles,gapReadings).filter(e=>e.kind==='signal').length,1);
const refillAt=demoNow+1200000;
const afterRefill=plantState(sample,[...sample.history,{...sample.history.at(-1),measured_at:new Date(refillAt).toISOString(),weight_g:629}],{now:refillAt});
assert.equal(afterRefill.state,'refill');
assert.equal(afterRefill.setupRetired,true);
assert.equal(afterRefill.percent,null);
const fullDial=plantDrydownGauge(afterRefill,629);
assert.equal(fullDial.angle,495);
assert.equal(fullDial.label,'Refilled');
const withLearnedDry=plantState({...sample,learned_dry_g:500},sample.history,{now:demoNow});
assert.equal(withLearnedDry.setupRetired,false);
assert.equal(withLearnedDry.dry,500);
assert.ok(withLearnedDry.percent>0);
const dip=[...Array.from({length:20},(_,i)=>row((21-i)*20,530-i*.1)),row(20,0),row(0,519)];
assert.equal(plantState(plant,dip,{now}).setupRetired,false);
const gap=sample.history.filter(r=>{
  const age=below.previousLow.at-Date.parse(r.measured_at);
  return age<4*3600000||age>8*3600000;
});
const interrupted=plantState(sample,gap,{now:demoNow});
assert.equal(interrupted.previousLow,null);
assert.equal(interrupted.percent,null);
assert.ok(interrupted.rate>0);
assert.equal(reservePercentLabel(plantState(plant,[row(0,525.1)],{now}).percent),'<1%');
assert.equal(waterPlan({current:519.6,addition:2,dry:525,wet:629,rate:12}).days,null);
console.log('Passed: plant states, reserve and weight projections, and previous cycle comparison with uninterrupted data.');
