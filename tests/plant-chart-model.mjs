import assert from 'node:assert/strict';
import {plantState} from '../plant-state.js';
import {plantChartModel} from '../plant-chart-model.js';
const now=Date.parse('2026-10-21T01:00:00Z');
const row=(hours,w,run='one')=>({weight_g:w,measured_at:new Date(now-hours*3600000).toISOString(),run_id:run});
const readings=[row(73,540),...Array.from({length:217},(_,i)=>row(72-i/3,640-i*.19))];
const view=plantState({provisional_dry_g:525,learned_saturated_g:640},readings,{now});
const cycle=plantChartModel(readings,view);
assert.equal(cycle.start,now-73*3600000);assert.equal(cycle.refill.weight_g,640);
assert.equal(cycle.pot.at(-1).weight_g,598.96);assert.equal(cycle.hi,640);assert.equal(cycle.lo,525);
const day=plantChartModel(readings,view,{range:'24'});
assert.equal(day.pot.length,73);assert.equal(day.refill,null);assert.equal(day.hi,640);assert.equal(day.lo,525);
const next=readings.concat(row(-1/3,598.7));
const nextView=plantState({provisional_dry_g:525,learned_saturated_g:640},next,{now:now+1200000});
assert.equal(plantChartModel(next,nextView).hi,cycle.hi);assert.equal(plantChartModel(next,nextView).lo,cycle.lo);
const lifted=[row(3,540),row(2.8,0),row(2.6,650),row(2.3,640),row(0,638)];
const lift=plantChartModel(lifted,plantState({provisional_dry_g:525,learned_saturated_g:640},lifted,{now}));
assert.equal(lift.pot.length,4);assert.equal(lift.rows.length,5);assert.equal(lift.hi,650);assert.equal(lift.lo,525);assert.equal(lift.start,now-3*3600000);
const noRefill=[row(200,620),row(160,610),row(0,600),row(1,999,'old')];
const fallback=plantChartModel(noRefill,plantState({},noRefill,{now}));
assert.equal(fallback.cycleFound,false);assert.equal(fallback.pot.length,2);assert.equal(fallback.hi,610);assert.equal(fallback.refill,null);
assert.deepEqual(plantChartModel([],plantState({},[],{now})).pot,[]);
console.log('Passed: three-day watering peak, stable reference axes, manual ranges, pot-lift gap, over-full peaks, missing-refill fallback and run isolation.');
