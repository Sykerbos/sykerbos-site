import assert from 'node:assert/strict';
import {saveWateringWeight,wateringDisplayRows} from '../watering-handoff.js';
import {plantState} from '../plant-state.js';
const memory=new Map();
const storage={getItem:k=>memory.get(k)??null,setItem:(k,v)=>memory.set(k,v),removeItem:k=>memory.delete(k)};
const now=Date.parse('2026-11-14T03:15:00Z');
const context={userId:'owner',plantId:'a',deviceId:'mini01',deviceCode:'Mini01',runId:'run-a'};
const rows=Array.from({length:30},(_,i)=>({weight_g:510-i*.1,measured_at:new Date(now-(30-i)*1200000).toISOString(),run_id:'run-a',temperature_c:21}));
const original=JSON.stringify(rows);
const save=()=>saveWateringWeight(context,{weight:620.3,measuredAt:now-20},{storage,now});
assert.equal(save(),true);
const pending=wateringDisplayRows(context,rows,{storage,now});
assert.equal(pending.at(-1).weight_g,620.3);
assert.equal(pending.at(-1).source,'live-watering');
assert.equal(pending.at(-1).temperature_c,null);
assert.equal(JSON.stringify(rows),original);
const view=plantState({provisional_dry_g:500,learned_saturated_g:640},pending,{now});
assert.equal(view.latest.w,620.3);assert.equal(view.state,'refill');assert.equal(view.rate,null);
for(const field of ['userId','plantId','deviceId','deviceCode']){
 const other={...context,[field]:'other'};
 assert.equal(wateringDisplayRows(other,rows,{storage,now}),rows);
}
save();
const earlier=[...rows,{...rows.at(-1),measured_at:new Date(now-600000).toISOString()}];
assert.equal(wateringDisplayRows(context,earlier,{storage,now}).at(-1).source,'live-watering');
const uploaded=[...rows,{...rows.at(-1),weight_g:619.8,measured_at:new Date(now+1000).toISOString()}];
assert.equal(wateringDisplayRows(context,uploaded,{storage,now:now+2000}),uploaded);
assert.equal(memory.size,0);
save();
const changedRun=[{...rows.at(-1),run_id:'new-run'}];
assert.equal(wateringDisplayRows(context,changedRun,{storage,now}),changedRun);assert.equal(memory.size,0);
save();assert.equal(wateringDisplayRows(context,rows,{storage,now:now+90*60000}),rows);assert.equal(memory.size,0);
assert.equal(saveWateringWeight(context,{weight:620,measuredAt:now-4000},{storage,now}),false);
assert.equal(saveWateringWeight(context,{weight:0,measuredAt:now},{storage,now}),false);
assert.equal(saveWateringWeight(context,{weight:null,measuredAt:now},{storage,now}),false);
assert.equal(saveWateringWeight(context,{weight:620,measuredAt:now+1000},{storage,now}),false);
const blocked={getItem(){throw Error('blocked');},setItem(){throw Error('blocked');}};
assert.equal(saveWateringWeight(context,{weight:620,measuredAt:now},{storage:blocked,now}),false);
assert.equal(wateringDisplayRows(context,rows,{storage:blocked,now}),rows);
console.log('Passed: live weight handoff, fresh on-pot capture, identity/run isolation, cloud replacement, expiry and storage failures.');
