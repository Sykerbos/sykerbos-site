import assert from 'node:assert/strict';
import {transientWeightSpikes} from '../reading-quality.js';
import {irrigationState} from '../irrigation-state.js';
import {plantChartModel} from '../plant-chart-model.js';
import {plantState} from '../plant-state.js';
const now=Date.parse('2026-10-21T01:00:00Z');
const weights=[529.9,11.5,641.2,639.8,656.2,636.6,633.4,629,630.9,629.3,628.1,628.1,798.6,635.6,650.4,631.1,628.4];
const rows=weights.map((weight_g,i)=>({weight_g,measured_at:new Date(now-(weights.length-1-i)*1200000).toISOString(),run_id:'one'}));
const original=JSON.stringify(rows),plant={provisional_dry_g:525,learned_saturated_g:629};
const view=plantState(plant,rows,{now});
assert.equal(view.cycle.refill.after,641.2);
assert.equal(view.cycle.refill.at,Date.parse(rows[2].measured_at));
const model=plantChartModel(rows,view);
assert.equal(model.hi,641.2);assert.equal(model.lo,525);assert.equal(model.excludedSpikes,3);
assert.ok(!model.pot.some(r=>r.weight_g===798.6||r.weight_g===11.5));
assert.equal(JSON.stringify(rows),original);
const opts={dry:525,wet:629,emptyFloor:262.5};
const sample=values=>values.map((weight_g,i)=>({weight_g,t:now+i*1200000,run_id:'one'}));
assert.equal(transientWeightSpikes(sample([530,700,699,698]),opts).size,0,'sustained over-full gain stays visible');
assert.equal(transientWeightSpikes(sample([530,640,639]),opts).size,0,'real watering retained');
assert.equal(transientWeightSpikes(sample([628,799]),opts).size,0,'unconfirmed latest peak stays visible');
assert.equal(transientWeightSpikes(sample([628,0,629]),opts).size,0,'empty tile is separate');
const gap=sample([628,799,635]);gap[2].t+=2*3600000;
assert.equal(transientWeightSpikes(gap,opts).size,0,'no inference across long gap');
const mixed=sample([628,799,635]);mixed[2].run_id='two';
assert.equal(transientWeightSpikes(mixed,opts).size,0,'no inference across runs');
console.log('Passed: actual Mini02 sequence excludes 798.6 g handling spike, retains first watering, raw data, real over-full gains and unconfirmed peaks.');
